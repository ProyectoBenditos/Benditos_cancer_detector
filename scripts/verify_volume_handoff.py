"""Verify the delivered snapshot using only Python's standard library.

This is an integrity check, not an inference or clinical validation run.
The reference manifest is intentionally not regenerated by this script.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default="docs/volume-rendering/handoff-2026-10-22/run-manifest.json")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    manifest = json.loads((root / args.manifest).read_text(encoding="utf-8-sig"))
    problems = []
    verified = 0
    missing_optional = []
    for artifact in manifest["artifacts"]:
        relative = artifact["path"]
        path = (root / relative).resolve()
        if not path.is_relative_to(root):
            problems.append({"path": relative, "problem": "outside_repository"})
            continue
        if not path.is_file():
            if artifact.get("required", True):
                problems.append({"path": relative, "problem": "missing"})
            else:
                missing_optional.append(relative)
            continue
        digest = hashlib.sha256()
        if artifact.get("sha256_mode") == "lf_text":
            # Git checkouts can use CRLF on Windows and LF on Linux.
            digest.update(path.read_bytes().replace(b"\r\n", b"\n"))
        else:
            with path.open("rb") as source:
                for block in iter(lambda: source.read(1024 * 1024), b""):
                    digest.update(block)
        if digest.hexdigest() != artifact["sha256"]:
            problems.append({"path": relative, "problem": "sha256_mismatch"})
        else:
            verified += 1
    print(json.dumps({"scope": "snapshot_integrity_only", "verified": verified,
        "missing_optional": missing_optional, "problems": problems,
        "status": "pass" if not problems else "fail"}, ensure_ascii=False, indent=2))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
